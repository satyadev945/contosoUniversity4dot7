        private const string BaselineProductVersion = "10.0.0";

        public static async Task InitializeAsync(SchoolContext context, ILogger logger)
        {
            await BaselineLegacyDatabaseAsync(context, logger);
            await context.Database.MigrateAsync();
            await SeedAsync(context);
        }

        /// <summary>
        /// A database created by EF6 already contains the schema (and a __MigrationHistory table) but
        /// has no __EFMigrationsHistory table. Mark the first EF Core migration as applied so that the
        /// existing schema and data are preserved.
        /// </summary>
        private static async Task BaselineLegacyDatabaseAsync(SchoolContext context, ILogger logger)
        {
            if (!await context.Database.CanConnectAsync())
            {
                return;
            }

            var applied = (await context.Database.GetAppliedMigrationsAsync()).ToList();
            if (applied.Count > 0)
            {
                return;
            }

            var legacyTables = await context.Database
                .SqlQueryRaw<int>("SELECT COUNT(*) AS [Value] FROM sys.tables WHERE name IN (N'__MigrationHistory', N'Student', N'Course')")
                .ToListAsync();

            if (legacyTables.Count == 0 || legacyTables[0] < 3)
            {
                return;
            }

            var baselineMigration = context.Database.GetMigrations().FirstOrDefault();
            if (baselineMigration == null)
            {
                return;
            }

            logger.LogInformation("Legacy EF6 database detected. Baselining with migration {Migration}.", baselineMigration);

            var historyRepository = context.GetService<IHistoryRepository>();
            var createScript = historyRepository.GetCreateIfNotExistsScript();
            var insertScript = historyRepository.GetInsertScript(new HistoryRow(baselineMigration, BaselineProductVersion));

#pragma warning disable EF1002 // Scripts are generated by EF Core and contain no user input.
            await context.Database.ExecuteSqlRawAsync(createScript);
            await context.Database.ExecuteSqlRawAsync(insertScript);
#pragma warning restore EF1002
        }

